#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

/* ==================================================================
   杨氏矩阵查找（鲸鱼娘版，注释写得比代码多，慢慢读喵）

   矩阵的性质（题目给的）：
     1) 每一行，从左到右递增
     2) 每一列，从上到下递增

   ------------------------------------------------------------------
   思路：一共就 4 步，你按这个顺序想，就不会乱。

   第 1 步：从哪个格子出发？
     选【右上角】。这个矩阵是 5 行 5 列，右上角就是 arr[0][4]。
     为什么是它？因为站在右上角，你面前只有两个方向：
         往左走 → 数字一定【变小】
         往下走 → 数字一定【变大】
     一个变小、一个变大，所以每比一次都能立刻确定方向，不犹豫。

     （如果你从左上角出发：往右、往下都是变大，比完根本不知道该走哪边。
       这就是大多数人卡在这题的原因。）

   第 2 步：每一步怎么走？
     把当前格子的数 arr[i][j] 和目标 num 比一比，只有三种结果：
         相等      → 找到了，返回 1
         arr[i][j] 比 num 大 → 目标只可能在【左边】，所以 j-- （往左走）
         arr[i][j] 比 num 小 → 目标只可能在【下边】，所以 i++ （往下走）

   第 3 步：什么时候停下来？
     一直走，直到格子跑出矩阵外面：
         i 到了行数（走完最后一行下面）
         j 小于 0（走过最左边）
     这时还没找到，就说明整个矩阵里没有这个数，返回 0。

   第 4 步：为什么这样算快？
     每一步要么 i 加 1，要么 j 减 1；
     从一个角走到另一个角，最多走 (行数-1) + (列数-1) 步。
     5×5 的矩阵最多 8 步，而不是把 25 个数挨个看一遍。
   ================================================================== */


/* 在矩阵里找 num：
     找到 返回 1
     没找到 返回 0
   参数说明：
     arr[][5] —— 二维数组当参数，必须写清楚"一行有几个数"（这里是 5），
                 行数可以不写。这就是上次学的 int (*arr)[5]。
     rows     —— 实际有几行（这里传 5）
     cols     —— 实际有几列（这里传 5）
     num      —— 要找的数
   （名字从 fac 改成 find，是因为这个函数干的事就是"找"，名字最好一眼看懂喵） */
int find(int arr[][5], int rows, int cols, int num)
{
	int i = 0;           /* 行号：从第 0 行开始（右上角在上面那行） */
	int j = cols - 1;    /* 列号：从最后一列开始（5 列 → 下标 4，就是右上角） */

	/* 只要还在矩阵里面，就继续走
	   i < rows  → 行号没超过最后一行
	   j >= 0    → 列号没走到左边外面 */
	while (i < rows && j >= 0)
	{
		if (arr[i][j] == num)          /* 正好相等：找到了 */
		{
			return 1;
		}
		else if (arr[i][j] > num)      /* 当前数太大 → 目标在左边 */
		{
			j--;                       /* 往左走一列 */
		}
		else                           /* 当前数太小 → 目标在下边 */
		{
			i++;                       /* 往下走一行 */
		}
	}

	/* 走到矩阵外面了还没找到 → 没有这个数 */
	return 0;
}


int main(void)
{
	/* 题目里的那个 5×5 矩阵（行、列都递增） */
	int arr[5][5] =
	{
		{ 1,  4,  7, 11, 15},
		{ 2,  5,  8, 12, 19},
		{ 3,  6,  9, 16, 22},
		{10, 13, 14, 17, 24},
		{18, 21, 23, 26, 30}
	};

	int num = 0;        /* 要找的数 */
	int found = 0;      /* 查找结果：1 = 找到，0 = 没找到 */

	printf("请输入你要找的数：");

	/* scanf 的返回值 = 成功读进来几个数
	   不等于 1 说明输入不合法（比如打了个字母），直接结束 */
	if (scanf("%d", &num) != 1)
	{
		printf("输入无效\n");
		return 1;
	}

	/* 注意这里传的是 arr，不是 arr[5][5]！
	   arr 会自动变成"指向第 0 行的指针"，类型正好是 int (*)[5] */
	found = find(arr, 5, 5, num);

	if (found == 1)
	{
		printf("%d 在矩阵里 → 找到了\n", num);
	}
	else
	{
		printf("%d 不在矩阵里 → 没找到\n", num);
	}

	return 0;
}

