#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

#define MAX_LEN 100   /* 数组最多能装多少个元素，同时也是输入个数的上限 */

/* --------------------------------------------------------------------------
 * 交换两个整数
 *
 * 参数必须是指针：swap(&x, &y) 才改得动调用者的变量。
 * 如果写成 swap(int a, int b)，那只是交换了两个副本，外面什么都没变
 * —— 这就是「值传递」和「传地址」的区别。
 * -------------------------------------------------------------------------- */
static void swap(int *a, int *b)
{
	int tmp = *a;   /* 先把 a 指向的那个值记下来 */
	*a = *b;        /* 把 b 指向的值，写进 a 指向的地方 */
	*b = tmp;       /* 再把记下来的旧值，写进 b 指向的地方 */
}

/* --------------------------------------------------------------------------
 * 冒泡排序（升序）
 *   arr : 待排序数组的首元素地址（数组当参数传进来时会自动退化成指针）
 *   n   : 元素个数
 *
 * 外层数「趟」：每跑完一趟，末尾就多一个已经归位的元素，所以内层可以少看几个。
 *   i = 0 趟：最大值被冒到 arr[n-1]
 *   i = 1 趟：次大值被冒到 arr[n-2]
 *   ...
 * 所以内层只比较到 j < n - 1 - i 就够了。
 * -------------------------------------------------------------------------- */
void bubble_sort(int *arr, int n)
{
	if (arr == NULL || n < 2)   /* 0 个或 1 个元素，本来就「有序」，直接走人 */
	{
		return;
	}

	for (int i = 0; i < n - 1; i++)          /* 最多 n-1 趟，最后一趟只剩一个元素不用比 */
	{
		int swapped = 0;                     /* 0 表示这一趟一次交换都没有 */

		for (int j = 0; j < n - 1 - i; j++)
		{
			/* 关键：只跟「右边邻居」比，这才是冒泡 */
			if (arr[j] > arr[j + 1])
			{
				swap(&arr[j], &arr[j + 1]);  /* 传地址进去，函数里才改得动原数组 */
				swapped = 1;                 /* 记下「本趟换过了」 */
			}
		}

		/* 一整趟都没换过 => 每个邻居都是「左边不大于右边」=> 已经有序，提前收工 */
		if (swapped == 0)
		{
			break;
		}
	}
}

/* --------------------------------------------------------------------------
 * 读入数组，返回实际读到的元素个数；返回 0 表示输入失败
 *   max ：最多允许输入多少个数（防止写入超过数组容量）
 *
 * 注意这个返回值：n 只有「交出去」，main 才知道该处理几个元素。
 * 原版的 n 是局部变量，读完就跟着函数一起消失了。
 * -------------------------------------------------------------------------- */
int scanf_arr(int *arr, int max)
{
	int n = 0;

	printf("请输入数组元素的个数：");
	if (scanf("%d", &n) != 1 || n <= 0 || n > max)
	{
		printf("输入无效：个数应在 1 ~ %d 之间\n", max);
		return 0;
	}

	printf("请依次输入 %d 个整数（用空格或回车隔开）：", n);
	for (int i = 0; i < n; i++)
	{
		if (scanf("%d", &arr[i]) != 1)   /* 读到非法字符就停，不要硬读下去 */
		{
			printf("第 %d 个数读取失败，只收到 %d 个\n", i + 1, i);
			return i;
		}
	}
	return n;
}

/* --------------------------------------------------------------------------
 * 打印数组
 *   const int *arr ：向调用者承诺「我只读，不改」，这样谁都能放心把数组交过来
 *   *arr++         ：等价于 *(arr++)，先取当前指向的值，再让指针往后走一格
 *                    （arr 本身是参数副本，改它不会影响外面的指针）
 * -------------------------------------------------------------------------- */
void print_arr(const int *arr, int n)
{
	for (int i = 0; i < n; i++)
	{
		printf("%d ", *arr++);
	}
	printf("\n");
}

int main(void)
{
	int arr[MAX_LEN] = { 0 };        /* 全部初始化成 0，免得调试时被垃圾值骗 */
	int n;

	n = scanf_arr(arr, MAX_LEN);     /* 拿到真正读到的个数 */
	if (n <= 0)
	{
		return 1;                    /* 输入失败就直接退出，别拿垃圾数据排序 */
	}

	printf("排序前：");
	print_arr(arr, n);

	/* 数组名 arr 在表达式里就是首元素地址，等价于 &arr[0] */
	bubble_sort(arr, n);

	printf("排序后：");
	print_arr(arr, n);

	return 0;
}
