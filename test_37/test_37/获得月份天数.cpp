#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

/* ------------------------------------------------------------
 * 判断闰年：能被 400 整除，或者能被 4 整除但不能被 100 整除
 * 单独抽成一个函数，是因为它以后会被反复用到，别再抄两遍。
 * ------------------------------------------------------------ */
static int is_leap(int years)
{
	return (years % 400 == 0) || (years % 4 == 0 && years % 100 != 0);
}

/* ------------------------------------------------------------
 * 返回某年某月有多少天
 *
 * 思路：把 12 个月的天数存进一张表，用月份当下标直接查。
 *   下标 0 空着不用（这样 1 月就是 days[1]，读代码的人不用-1）
 *   2 月先按 28 天放，闰年再单独改成 29。
 *
 * 这样写的好处：没有"大月小月"的重复判断——你原来那套
 * "奇数月 31、偶数月 30，8 月以后反过来"其实是对的，
 * 但闰年和平年各写一遍，等于同一段逻辑抄了两次，改起来容易漏。
 * ------------------------------------------------------------ */
static int numsofdays(int years, int months)
{
	static const int days[13] = {
		0,                              /* 占位，让下标和月份对齐 */
		31, 28, 31, 30, 31, 30,         /* 1 - 6 月 */
		31, 31, 30, 31, 30, 31          /* 7 - 12 月 */
	};
	int d;

	/* 防御：月份不合法就不乱给数（题目保证 1-12，这里只是保险） */
	if (months < 1 || months > 12)
		return -1;

	d = days[months];                    /* 先按平年查表 */

	/* 只有 2 月需要因为闰年而改 */
	if (months == 2 && is_leap(years))
		d = 29;

	return d;
}

int main(void)
{
	int years = 0;
	int months = 0;

	/* --------------------------------------------------------
	 * 关键的一行：多组输入。
	 *
	 * scanf 的返回值 = "成功读到了几个数"。
	 *   读到 2 个 -> 继续处理
	 *   读到 1 个或 0 个（比如输入坏了）-> 不是 2，循环停下
	 *   读到 EOF（输入结束）-> 返回 -1，也不等于 2，循环停下
	 *
	 * 你原来的写法只读一次，评测机喂第二组数据时程序早就结束了，
	 * 所以只能过第一组。这是这道题最容易丢分的地方。
	 * -------------------------------------------------------- */
	while (scanf("%d %d", &years, &months) == 2)
	{
		int result = numsofdays(years, months);

		if (result == -1)
			printf("0\n");               /* 月份非法时的兜底输出 */
		else
			printf("%d\n", result);
	}

	return 0;
}
