#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

/*
 * 作业 1562 · 找单身狗2
 * ---------------------------------------------------------------------------
 * 题目：数组里只有两个数出现一次，其余都出现两次，找出这两个数。
 *
 * 你原来写的版本（只算了全体异或，然后 printf 出来）其实已经完成了第一步：
 *     all = 5 ^ 6 = 3
 * 但 3 是「两根线拧在一起」，不是答案。要把它们拆开，需要三小步：
 *
 * 第 1 步：全体异或 —— 成对的自己消成 0，剩下的就是 a ^ b。
 * 第 2 步：找 a ^ b 里最低位的那个 1（记作 lowbit）。
 *          a 和 b 是不同的数，所以它们至少有一位不同；这一位上，
 *          a 是 1、b 是 0（或反过来）。这就是「能用来分家的那把刀」。
 * 第 3 步：拿 lowbit 把整个数组分成两堆 ——
 *          这一位是 1 的进左边，是 0 的进右边。
 *          成对的数一定进同一堆，所以每堆各自异或，剩下的就是答案。
 *
 * 关键点：不需要真开两个数组！只要两个累加变量 x 和 y 就够了（O(1) 空间）。
 * ---------------------------------------------------------------------------
 */

/* 小工具：把数组打印成 [1, 2, 3] 的样子，方便看输入 */
static void print_arr(const int *arr, int n)
{
    printf("[");
    for (int i = 0; i < n; i++)
    {
        printf("%s%d", (i == 0) ? "" : ", ", arr[i]);
    }
    printf("]\n");
}

/*
 * 找单身狗2：把 arr 里只出现一次的两个数，通过 out1 / out2 带回去。
 *
 * 参数：
 *   const int *arr  只看不改，所以加 const（编译器会帮你挡住手滑的 arr[i] = 0）
 *   int length      元素个数
 *   int *out1       输出参数：第一个单身狗
 *   int *out2       输出参数：第二个单身狗
 *
 * 为什么用「输出参数」？因为 C 的函数只能 return 一个值，
 * 现在要带回两个数，就让调用者先把两个变量的地址交进来，我们往地址里写。
 * 用法：find_twosingle(arr, n, &a, &b);  之后 a、b 就拿到了答案。
 */
void find_twosingle(const int *arr, int length, int *out1, int *out2)
{
    /* ---------- 第 1 步：全体异或 ---------- */
    int all = 0;                   /* 异或的「单位元」是 0：0 ^ x 还是 x */
    for (int i = 0; i < length; i++)
    {
        all ^= arr[i];             /* 成对的数会互相抵消成 0，只剩 a ^ b */
    }

    /* 防护：如果 all 是 0，说明根本没有两个「各出现一次」的数（输入不合法） */
    if (all == 0)
    {
        *out1 = 0;
        *out2 = 0;
        return;
    }

    /* ---------- 第 2 步：取出最低位的 1 ---------- */
    /* all     = 3  -> 0000 0011
     * -all    = -3 -> 补码是 1111 1101
     * all&-all     -> 0000 0001  == 1
     *
     * 换个例子：all = 12 -> 1100，-12 -> 0100（补码），与一下得 0100 = 4。
     * 这招在 C 里到处用，叫 lowbit。*/
    int lowbit = all & (-all);

    /* ---------- 第 3 步：按 lowbit 分两堆，各自异或 ---------- */
    int x = 0;                     /* 这一位是 1 的那堆 */
    int y = 0;                     /* 这一位是 0 的那堆 */

    for (int i = 0; i < length; i++)
    {
        /* 注意这里用 & 判断「这一位是 1 吗」，不是 == */
        if ((arr[i] & lowbit) != 0)
        {
            x ^= arr[i];           /* 成对的会抵消，最后留下单身的那一个 */
        }
        else
        {
            y ^= arr[i];
        }
    }

    /* 把结果写回调用者给的地址里 */
    *out1 = x;
    *out2 = y;
}

int main(void)
{
    /* ---- 测试 1：题目给的例子 ---- */
    int arr[10] = { 1, 2, 3, 4, 5, 1, 2, 3, 4, 6 };
    int n = (int)(sizeof(arr) / sizeof(arr[0]));   /* 40 / 4 = 10 */
    int a = 0;
    int b = 0;

    print_arr(arr, n);
    find_twosingle(arr, n, &a, &b);
    printf("  -> 两个单身狗是 %d 和 %d\n\n", a, b);

    /* ---- 测试 2：只有一对 + 两个单身狗 ---- */
    int arr2[4] = { 7, 7, 12, 20 };
    int n2 = (int)(sizeof(arr2) / sizeof(arr2[0]));
    int c = 0;
    int d = 0;

    print_arr(arr2, n2);
    find_twosingle(arr2, n2, &c, &d);
    printf("  -> 两个单身狗是 %d 和 %d\n\n", c, d);

    /* ---- 测试 3：带负数（证明异或不挑正负） ---- */
    int arr3[6] = { -5, 3, 3, -5, 100, 7 };
    int n3 = (int)(sizeof(arr3) / sizeof(arr3[0]));
    int e = 0;
    int f = 0;

    print_arr(arr3, n3);
    find_twosingle(arr3, n3, &e, &f);
    printf("  -> 两个单身狗是 %d 和 %d\n", e, f);

    return 0;
}

